(def round-trip-ddl
  "CREATE SCHEMA rt_src;
   CREATE TABLE rt_src.users (
     id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
     email text NOT NULL,
     tags text[] DEFAULT '{a,b}',
     double_id integer GENERATED ALWAYS AS (id * 2) STORED,
     CONSTRAINT users_email_key UNIQUE (email)
   );
   CREATE TABLE rt_src.orders (
     id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
     user_id integer NOT NULL REFERENCES rt_src.users(id) ON DELETE CASCADE,
     amount numeric(10,2) CHECK (amount >= 0),
     status text DEFAULT 'new' NOT NULL
   );
   ALTER TABLE rt_src.orders ADD CONSTRAINT orders_user_id_fk2 FOREIGN KEY (user_id) REFERENCES rt_src.users(id) NOT VALID;
   CREATE UNIQUE INDEX orders_user_amount_idx ON rt_src.orders (user_id, amount);
   CREATE INDEX orders_status_idx ON rt_src.orders (status) WHERE status <> 'done';
   CREATE VIEW rt_src.v_orders AS SELECT o.id, u.email, o.amount FROM rt_src.orders o JOIN rt_src.users u ON u.id = o.user_id;
   CREATE MATERIALIZED VIEW rt_src.mv_orders AS SELECT user_id, sum(amount) AS total FROM rt_src.orders GROUP BY user_id;
   CREATE FUNCTION rt_src.add_one(x integer) RETURNS integer LANGUAGE sql IMMUTABLE AS $$ SELECT x + 1 $$;
   CREATE FUNCTION rt_src.trigger_fn() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
   CREATE TRIGGER users_before BEFORE INSERT ON rt_src.users FOR EACH ROW EXECUTE FUNCTION rt_src.trigger_fn();
   COMMENT ON TABLE rt_src.users IS 'app users';
   COMMENT ON COLUMN rt_src.users.email IS 'email address';")

(defn- execute! [sql]
  (jdbc/execute! db [sql]))

(defn- normalize-schema
  "Replace a schema name with a placeholder so two schemas can be compared."
  [schema row]
  (into {}
        (map (fn [[k v]]
               [k (if (string? v) (str/replace v schema "SCHEMA") v)]))
        row))

(defn- catalog-snapshot
  "Collect the catalog facts that synthesized DDL should reproduce, with the
  schema name normalized out so source and replayed schemas compare equal."
  [schema]
  (let [q (fn [sql] (map #(normalize-schema schema %) (jdbc/execute! db sql)))]
    {:columns
     (q [(str "SELECT c.relname AS tbl, a.attname AS col, "
              "format_type(a.atttypid, a.atttypmod) AS typ, "
              "a.attnotnull AS not_null, a.attidentity::text AS identity_kind, "
              "a.attgenerated::text AS generated_kind, "
              "pg_get_expr(d.adbin, d.adrelid, true) AS default_value "
              "FROM pg_attribute a "
              "JOIN pg_class c ON c.oid = a.attrelid "
              "JOIN pg_namespace n ON n.oid = c.relnamespace "
              "LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
              "WHERE n.nspname = ? AND a.attnum > 0 AND c.relkind IN ('r','p') "
              "ORDER BY c.relname, a.attnum")
         schema])

     :constraints
     (q [(str "SELECT c.relname AS tbl, con.conname AS name, con.contype AS type, "
              "pg_get_constraintdef(con.oid, true) AS definition "
              "FROM pg_constraint con "
              "JOIN pg_class c ON c.oid = con.conrelid "
              "JOIN pg_namespace n ON n.oid = c.relnamespace "
              "WHERE n.nspname = ? AND con.contype IN ('p','u','f','c') "
              "ORDER BY c.relname, con.conname")
         schema])

     :indexes
     (q [(str "SELECT pg_get_indexdef(i.indexrelid) AS definition "
              "FROM pg_index i "
              "JOIN pg_class c ON c.oid = i.indrelid "
              "JOIN pg_namespace n ON n.oid = c.relnamespace "
              "LEFT JOIN pg_constraint con ON con.conindid = i.indexrelid "
              "WHERE n.nspname = ? AND con.conindid IS NULL AND NOT i.indisprimary "
              "ORDER BY definition")
         schema])

     :views
     (q [(str "SELECT c.relname AS name, c.relkind AS kind, "
              "pg_get_viewdef(c.oid, true) AS definition "
              "FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
              "WHERE n.nspname = ? AND c.relkind IN ('v','m') "
              "ORDER BY c.relname")
         schema])

     :functions
     (q [(str "SELECT p.proname AS name, pg_get_functiondef(p.oid) AS definition "
              "FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
              "WHERE n.nspname = ? AND p.prokind IN ('f','p') "
              "ORDER BY p.proname")
         schema])

     :triggers
     (q [(str "SELECT pg_get_triggerdef(t.oid, true) AS definition "
              "FROM pg_trigger t "
              "JOIN pg_class c ON c.oid = t.tgrelid "
              "JOIN pg_namespace n ON n.oid = c.relnamespace "
              "WHERE n.nspname = ? AND NOT t.tgisinternal "
              "ORDER BY definition")
         schema])

     :comments
     (q [(str "SELECT c.relname AS tbl, obj_description(c.oid, 'pg_class') AS table_comment, "
              "a.attname AS col, col_description(c.oid, a.attnum) AS column_comment "
              "FROM pg_class c "
              "JOIN pg_namespace n ON n.oid = c.relnamespace "
              "LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 "
              "WHERE n.nspname = ? AND c.relkind = 'r' "
              "AND (obj_description(c.oid, 'pg_class') IS NOT NULL "
              "     OR col_description(c.oid, a.attnum) IS NOT NULL) "
              "ORDER BY c.relname, a.attnum")
         schema])}))

(deftest round-trip-test
  (testing "generated DDL reproduces the source schema's catalog facts"
    (execute! "DROP SCHEMA IF EXISTS rt_src CASCADE; DROP SCHEMA IF EXISTS rt_dst CASCADE")
    (execute! round-trip-ddl)
    (let [generated (ddl/generate-ddl db :schemas ["rt_src"])
          ;; replay into a fresh schema by remapping the schema name
          replayed  (str/replace generated "rt_src" "rt_dst")
          _         (execute! "CREATE SCHEMA rt_dst")
          _         (execute! replayed)]
      (is (= (catalog-snapshot "rt_src") (catalog-snapshot "rt_dst"))))))

(deftest shape-tests
  (testing "per-object DDL entry points return the expected statement shape"
    (execute! "DROP SCHEMA IF EXISTS shape_src CASCADE; CREATE SCHEMA shape_src")
    (execute! (str "CREATE TABLE shape_src.t (id integer PRIMARY KEY, "
                   "name text NOT NULL DEFAULT 'x'::text)"))
    (execute! "CREATE VIEW shape_src.v AS SELECT id FROM shape_src.t")
    (execute! "CREATE FUNCTION shape_src.f() RETURNS integer LANGUAGE sql AS $$ SELECT 1 $$")

    (is (str/includes? (ddl/ddl-for-table db "shape_src" "t")
                       "CREATE TABLE \"shape_src\".\"t\""))
    (is (str/includes? (ddl/ddl-for-view db "shape_src" "v")
                       "CREATE VIEW \"shape_src\".\"v\""))
    (is (str/includes? (ddl/ddl-for-function db "shape_src" "f")
                       "CREATE OR REPLACE FUNCTION shape_src.f()"))))

(deftest system-object-exclusion-test
  (testing "generate-ddl excludes pg_catalog and information_schema by default"
    (let [out (ddl/generate-ddl db)]
      (is (not (str/includes? out "pg_catalog")))
      (is (not (str/includes? out "information_schema"))))))

(deftest empty-db-test
  (testing "generate-ddl on a database with no user objects is deterministic"
    (let [out (ddl/generate-ddl db :schemas ["public"])]
      (is (string? out))
      (is (= "" out)))))
