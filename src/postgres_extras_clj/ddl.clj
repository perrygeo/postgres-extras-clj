(ns postgres-extras-clj.ddl
  "Synthesize CREATE/ALTER DDL from the current state of a live database.
  PostgreSQL stores only the parsed representation of DDL statements.
  This namespace reverse-engineers the effective DDL from the system catalogs."
  (:require [clojure.string :as str]
            [postgres-extras-clj.core :as pgex]))

;;;
;;; Rendering helpers
;;;

(defn- quote-ident
  "Double-quote a SQL identifier, doubling any embedded quotes."
  [s]
  (str "\"" (str/replace (str s) "\"" "\"\"") "\""))

(defn- qualified
  "Schema-qualified, quoted identifier"
  [schema name]
  (str (quote-ident schema) "." (quote-ident name)))

(defn- escape-sql-literal
  "Escape a string for use inside a single-quoted SQL literal."
  [s]
  (str/replace (str s) "'" "''"))

(defn- strip-trailing-semicolon
  "Remove a single trailing semicolon (and surrounding whitespace)"
  [s]
  (str/replace (str s) #";\s*$" ""))

(defn- ensure-semicolon
  "Trim a decompiled definition and make sure it ends with exactly one semicolon."
  [s]
  (let [t (str/trimr (str s))]
    (if (str/ends-with? t ";")
      t
      (str t ";"))))

(defn- render-column
  "Render one column definition for a CREATE TABLE body."
  [{:keys [column data_type collation generated_kind identity_kind
           default_value not_null]}]
  (str "    " (quote-ident column) " " data_type
       (when collation (str " COLLATE " collation))
       (cond
         (= "stored" generated_kind) (str " GENERATED ALWAYS AS (" default_value ") STORED")
         (= "always" identity_kind) " GENERATED ALWAYS AS IDENTITY"
         (= "by default" identity_kind) " GENERATED BY DEFAULT AS IDENTITY"
         (some? default_value) (str " DEFAULT " default_value))
       (when not_null " NOT NULL")))

(defn- render-create-table
  "Assemble a bare CREATE TABLE statement from its column rows and options."
  [cols {:keys [schema table persistence storage_params tablespace partition_by]}]
  (str (if (= "u" persistence) "CREATE UNLOGGED TABLE " "CREATE TABLE ")
       (qualified schema table)
       " (\n"
       (str/join ",\n" (map render-column (sort-by :position cols)))
       "\n)"
       (when partition_by (str " PARTITION BY " partition_by))
       (when (seq storage_params) (str " WITH (" storage_params ")"))
       (when tablespace (str " TABLESPACE " (quote-ident tablespace)))
       ";"))

(defn- render-constraint
  "ALTER TABLE ... ADD CONSTRAINT, using pg_get_constraintdef verbatim."
  [{:keys [schema table constraint definition]}]
  (str "ALTER TABLE ONLY " (qualified schema table)
       "\n    ADD CONSTRAINT " (quote-ident constraint) " " definition ";"))

(defn- render-view
  "Wrap a pg_get_viewdef SELECT in CREATE [MATERIALIZED] VIEW."
  [{:keys [schema view kind definition]}]
  (let [q   (qualified schema view)
        sel (strip-trailing-semicolon definition)]
    (if (= "m" kind)
      (str "CREATE MATERIALIZED VIEW " q " AS\n" sel "\n  WITH NO DATA;")
      (str "CREATE VIEW " q " AS\n" sel ";"))))

(defn- render-comment
  "COMMENT ON TABLE/VIEW/COLUMN from obj_description / col_description."
  [{:keys [schema object object_type column comment]}]
  (let [kind   (case object_type
                 "table" "TABLE"
                 "view" "VIEW"
                 "materialized view" "MATERIALIZED VIEW"
                 "foreign table" "FOREIGN TABLE"
                 "column" "COLUMN"
                 "TABLE")
        target (if (= "column" object_type)
                 (str (qualified schema object) "." (quote-ident column))
                 (qualified schema object))]
    (str "COMMENT ON " kind " " target " IS '" (escape-sql-literal comment) "';")))

;;;
;;; Per-object entry points
;;;

(defn ddl-for-table
  "Return the CREATE TABLE statement for a table in a schema."
  [db schema table]
  (let [opts (first (filter #(and (= schema (:schema %)) (= table (:table %)))
                            (pgex/ddl-table-options db)))
        cols (filter #(and (= schema (:schema %)) (= table (:table %)))
                     (pgex/ddl-table-columns db))]
    (when opts
      (render-create-table cols opts))))

(defn ddl-for-view
  "Return the CREATE [MATERIALIZED] VIEW statement for a view in a schema."
  [db schema view]
  (let [v (first (filter #(and (= schema (:schema %)) (= view (:view %)))
                         (pgex/ddl-view-defs db)))]
    (when v
      (render-view v))))

(defn ddl-for-function
  "Return the CREATE OR REPLACE FUNCTION/PROCEDURE statement for a function
  (or procedure) in a schema. Matches by function name; for overloaded
  functions this returns the first match. TODO"
  [db schema fn]
  (let [f (first (filter #(and (= schema (:schema %)) (= fn (:function %)))
                         (pgex/ddl-function-defs db)))]
    (when f
      (str/trimr (:definition f)))))

;;;
;;; Whole-database generation
;;;

(defn- in-schemas? [schemas row]
  (or (nil? schemas) (contains? (set schemas) (:schema row))))

(defn- keep-object? [include-system-objects? schemas row]
  (and (or include-system-objects? (not (:system_object row)))
       (in-schemas? schemas row)))

(defn generate-ddl
  "Generate a full-database DDL script as a single string, composed in dependency order
  (tables -> constraints -> indexes -> views -> functions -> triggers -> rules -> comments).

  Options:
    :include-system-objects?  emit pg_catalog/information_schema objects (default false)
    :schemas                  restrict output to a vector of schema names"
  [db & {:keys [include-system-objects? schemas]
         :or   {include-system-objects? false}}]
  (let [keep?               (partial keep-object? include-system-objects? schemas)
        tables              (sort-by (juxt :schema :table) (filter keep? (pgex/ddl-table-options db)))
        columns             (filter keep? (pgex/ddl-table-columns db))
        constraints         (filter keep? (pgex/ddl-table-constraints db))
        indexes             (filter keep? (pgex/ddl-index-defs db))
        views               (filter keep? (pgex/ddl-view-defs db))
        functions           (filter keep? (pgex/ddl-function-defs db))
        triggers            (filter keep? (pgex/ddl-trigger-defs db))
        rules               (filter keep? (pgex/ddl-rule-defs db))
        comments            (filter keep? (pgex/ddl-comments db))
        cols-by-table       (group-by (juxt :schema :table) columns)
        ;; PK/unique/check before FK (type 'f' last), then deterministic order
        constraints-ordered (sort-by (juxt #(if (= "f" (:type %)) 1 0)
                                           :schema :table :constraint)
                                     constraints)]
    (str/join "\n\n"
              (concat
               (map #(render-create-table (get cols-by-table [(:schema %) (:table %)] []) %)
                    tables)
               (map render-constraint constraints-ordered)
               (map #(ensure-semicolon (:definition %)) indexes)
               (map render-view views)
               (map #(ensure-semicolon (:definition %)) functions)
               (map #(ensure-semicolon (:definition %)) triggers)
               (map #(ensure-semicolon (:definition %)) rules)
               (map render-comment comments)))))
